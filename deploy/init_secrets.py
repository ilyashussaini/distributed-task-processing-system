"""Create local Compose secrets without printing their values."""

import argparse
import re
import secrets
from getpass import getpass
from pathlib import Path

BCRYPT = re.compile(r"\$2[aby]\$\d{2}\$[./A-Za-z0-9]{53}")


def create_secrets(directory: Path, operator_hash: str) -> None:
    if not BCRYPT.fullmatch(operator_hash):
        raise ValueError("Expected a bcrypt hash generated by caddy hash-password.")
    directory.mkdir(mode=0o700)
    redis_password = secrets.token_hex(32)
    values = {
        "operator_hash": operator_hash,
        "api_token": secrets.token_hex(32),
        "postgres_password": secrets.token_hex(32),
        "redis_password": redis_password,
        "redis_acl": f"user default on >{redis_password} ~* &* +@all",
    }
    for name, value in values.items():
        path = directory / name
        with path.open("x") as file:
            file.write(value + "\n")
        # The protected directory is traversable only by its owner on the host.
        # The mount must be readable by the service UID inside the container.
        path.chmod(0o444)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--directory", type=Path, default=Path(__file__).parent / "secrets")
    args = parser.parse_args()
    operator_hash = getpass("Paste the Caddy bcrypt password hash: ").strip()
    try:
        create_secrets(args.directory, operator_hash)
    except (ValueError, FileExistsError) as exc:
        parser.exit(1, f"{exc}\n")
    print("Prepared secret files in a restricted directory.")


if __name__ == "__main__":
    main()
